local root = assert(vim.env.ZED_TEST_BUNDLE)
local project = vim.env.ZED_TEST_WORK .. '/project'
local child = vim.fn.jobstart({ root .. '/run', project, '--embed', 'example.py' }, { rpc = true })
assert(child > 0, 'Start Neovim')
local function call(code, ...) return vim.rpcrequest(child, 'nvim_exec_lua', code, { ... }) end
local function input(keys) vim.rpcrequest(child, 'nvim_input', keys) end
local function pause() vim.wait(150, function() return false end) end
local function wait(code, label, timeout)
  assert(vim.wait(timeout or 8000, function() return call(code) == true end, 20), label)
  print('PASS ' .. label)
end
local function check(ok, label) assert(ok, label); print('PASS ' .. label) end
local ok, err = pcall(function()
  vim.rpcrequest(child, 'nvim_ui_attach', 120, 40, { rgb = true })
  wait([[return #vim.api.nvim_list_wins()==2 and vim.bo.buftype=='' and vim.api.nvim_get_mode().mode=='n']], 'file startup omits terminal and focuses editor')
  check(call([[local icon=MiniIcons.get('file','example.py')
    local text=''; for _,w in ipairs(vim.api.nvim_list_wins()) do local b=vim.api.nvim_win_get_buf(w); if vim.bo[b].filetype=='NvimTree' then text=table.concat(vim.api.nvim_buf_get_lines(b,0,-1,false),' ') end end;
    return text:find(icon,1,true)~=nil and vim.api.nvim_eval_statusline(vim.o.tabline,{use_tabline=true,maxwidth=120}).str:find(icon,1,true)~=nil]]), 'file tree and tabline show file icons')
  input(' ')
  wait([[for _,w in ipairs(vim.api.nvim_list_wins()) do if vim.wo[w].winhighlight:find('MiniClue',1,true) then return true end end; return false]], 'Space shows shortcut hints')
  input('<Esc>')
  wait([[return #vim.api.nvim_list_wins()==2]], 'Escape closes shortcut hints')
  input('<C-p>')
  wait([[return MiniPick.is_picker_active()]], 'file search opens with icons')
  wait([[local icon=MiniIcons.get('file','example.py'); local b=MiniPick.get_picker_state().buffers.main; return table.concat(vim.api.nvim_buf_get_lines(b,0,-1,false),' '):find(icon,1,true)~=nil]], 'search results show file icons')
  input('<Esc>')
  wait([[return not MiniPick.is_picker_active()]], 'close file search')
  call([[for _,p in ipairs(vim.api.nvim_list_runtime_paths()) do assert(p:sub(1,#vim.env.NVIM_ZED_ROOT)==vim.env.NVIM_ZED_ROOT,p) end
    for _,kind in ipairs({'config','data','state','cache'}) do assert(vim.fn.stdpath(kind):find(vim.env.NVIM_ZED_ROOT..'/var/',1,true)==1) end]])
  print('PASS editor paths stay isolated after relocation')
  local marker = call([[local r=vim.system({'git','config','--global','--get','zedcheck.marker'},{text=true}):wait(); assert(r.code==0,r.stderr); return vim.trim(r.stdout)]])
  check(marker == 'host-settings-visible', 'Git subprocess sees original XDG configuration')
  local env_lines = call([=[return vim.fn.system([[printf '%s\n' "$XDG_CONFIG_HOME" "${XDG_DATA_HOME+set}:$XDG_DATA_HOME" "${XDG_CACHE_HOME-unset}" "${XDG_DATA_DIRS-unset}" "$XDG_STATE_HOME" "$XDG_CONFIG_DIRS"]])]=])
  local expected = table.concat({ vim.env.XDG_CONFIG_HOME, 'set:', 'unset', 'unset', vim.env.XDG_STATE_HOME, vim.env.XDG_CONFIG_DIRS, '' }, '\n')
  if env_lines ~= expected then print(vim.inspect({actual=env_lines,expected=expected,shell=call("return vim.o.shell"),code=call("return vim.v.shell_error")})) end
  check(env_lines == expected, 'shell restores set, empty and unset XDG variables')
  call([[vim.cmd('badd a.txt'); vim.cmd('badd b.txt'); vim.o.timeoutlen=2000]])
  input(' b')
  wait('return MiniPick.is_picker_active()', 'buffer picker has no prefix timeout', 1000)
  input('<Esc>')
  wait('return not MiniPick.is_picker_active()', 'close buffer picker')
  wait([[local c=vim.lsp.get_clients({name='ty',bufnr=0})[1]; return c~=nil and c.initialized]], 'ty attaches')
  input(' o')
  wait('return MiniPick.is_picker_active()', 'outline has no prefix timeout', 1000)
  input('greet')
  wait([[local m=MiniPick.get_picker_matches(); return table.concat(MiniPick.get_picker_query() or {})=='greet' and m~=nil and #m.all==1]], 'outline filtering')
  pause(); input('<CR>')
  wait([[return not MiniPick.is_picker_active() and vim.api.nvim_win_get_cursor(0)[1]==7]], 'outline selection jumps')
  wait([[local sources={}; for _,d in ipairs(vim.diagnostic.get(0)) do sources[d.source]=true end; return sources.ty==true and sources.Ruff==true]], 'ty and Ruff diagnostics')
  input(' q')
  wait([[return MiniPick.is_picker_active()]], 'Space q opens diagnostics')
  check(call([[local items=MiniPick.get_picker_items(); return #items>=2 and items[1].severity==vim.diagnostic.severity.ERROR]]), 'diagnostics sorted by severity')
  input("'wrong")
  wait([[local m=MiniPick.get_picker_matches(); return m~=nil and #m.all==1]], 'diagnostic list filtering')
  pause(); input('<CR>')
  wait([[return not MiniPick.is_picker_active() and vim.api.nvim_win_get_cursor(0)[1]==10]], 'diagnostic selection jumps to error')
  check(call([[return vim.fn.maparg('<Space>ci','n')~='' and vim.fn.maparg('<Space>oi','n')=='' and vim.fn.maparg('<Space>bd','n')=='']]), 'unambiguous updated shortcuts')
  input(' f')
  wait([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),string.char(10)):find('items = [1, 2, 3]',1,true)~=nil]], 'Ruff formatting')
  call([[vim.bo.modified=false]])
  input('<C-\\>')
  wait([[return vim.api.nvim_get_mode().mode=='t']], 'terminal created on demand')
  input('<C-k>')
  wait([[return vim.bo.buftype=='']], 'return from first terminal')
  local terminal = call([[for _,b in ipairs(vim.api.nvim_list_bufs()) do if vim.bo[b].buftype=='terminal' then return b end end]])
  local job = call('return vim.b[' .. terminal .. '].terminal_job_id')
  input('<C-j>')
  wait([[return vim.api.nvim_get_mode().mode=='t']], 'enter terminal')
  input([[printf 'SHELL_MARKER:'; git config --global --get zedcheck.marker<CR>]])
  wait([[for _,line in ipairs(vim.api.nvim_buf_get_lines(0,0,-1,false)) do if line=='SHELL_MARKER:host-settings-visible' then return true end end; return false]], 'terminal inherits user Git configuration')
  input('<Esc><Esc>')
  wait([[return vim.api.nvim_get_mode().mode:sub(1,1)=='n']], 'terminal normal mode')
  input(']b')
  wait([[return vim.bo.buftype=='' and vim.api.nvim_win_get_position(0)[1]==1]], 'buffer switching returns to editor')
  check(call('return vim.fn.bufwinid(' .. terminal .. ')~=-1 and vim.b[' .. terminal .. '].terminal_job_id==' .. job), 'buffer switch preserves terminal panel and job')
  input('<C-l>')
  wait([[return vim.bo.filetype=='NvimTree']], 'focus tree')
  input(' x')
  wait([[return vim.bo.buftype=='' and require('nvim-tree.api').tree.is_visible()]], 'close file operates in editor and preserves tree')
  check(call('return vim.fn.bufwinid(' .. terminal .. ')~=-1'), 'close file preserves terminal')
  input('<C-\\>')
  wait('return vim.fn.bufwinid(' .. terminal .. ')==-1', 'hide terminal')
  input('<C-\\>')
  wait([[return vim.api.nvim_get_mode().mode=='t']], 'restore terminal')
  check(call('return vim.b.terminal_job_id==' .. job), 'restore same shell process')
  input('<C-k>')
  wait([[return vim.bo.buftype=='']], 'terminal to editor')
  vim.rpcrequest(child, 'nvim_ui_try_resize', 140, 60)
  wait('return vim.api.nvim_win_get_height(vim.fn.bufwinid(' .. terminal .. '))==14', 'proportional resize')
  call([[vim.cmd('enew'); vim.bo.filetype='text'; vim.api.nvim_buf_set_lines(0,0,-1,false,{'start here','target one','between','target two'})]])
  input(' j'); input('t')
  local label
  check(vim.wait(5000, function()
    label=call([[for _,ns in pairs(vim.api.nvim_get_namespaces()) do for _,m in ipairs(vim.api.nvim_buf_get_extmarks(0,ns,0,-1,{details=true})) do if m[2]==3 then for _,chunk in ipairs(m[4].virt_text or {}) do if chunk[2]=='FlashLabel' then return chunk[1] end end end end end]])
    return type(label)=='string' and #label>0
  end,20), 'Flash labels')
  input(label)
  wait('return vim.api.nvim_win_get_cursor(0)[1]==4', 'Flash jump')
  input('<Esc>'); pause()
  call([[vim.api.nvim_buf_set_lines(0,0,-1,false,{'sharedLocal',''}); vim.api.nvim_win_set_cursor(0,{2,0})
    local same=vim.api.nvim_create_buf(true,false); vim.bo[same].filetype='text'; vim.api.nvim_buf_set_lines(same,0,-1,false,{'sharedOther'})
    local other=vim.api.nvim_create_buf(true,false); vim.bo[other].filetype='lua'; vim.api.nvim_buf_set_lines(other,0,-1,false,{'sharedWrongType'})]])
  input('i'); pause(); input('s'); pause(); input('h'); pause(); input('a'); pause()
  wait([[local cmp=require('cmp'); if not cmp.visible() then return false end; local labels={}; for _,e in ipairs(cmp.get_entries()) do labels[e:get_completion_item().label]=true end; return labels.sharedLocal==true and labels.sharedOther==true and labels.sharedWrongType==nil]], 'completion includes same type, excludes unrelated type')
  check(call([[return require('cmp').get_entries()[1]:get_completion_item().label=='sharedLocal']]), 'current buffer completion has priority')
  input('<Tab>')
  wait([[return vim.api.nvim_get_current_line()=='sharedLocal']], 'Tab accepts completion')
  input('<CR>')
  wait('return vim.api.nvim_buf_line_count(0)==3', 'Enter inserts newline')
  input('s'); pause(); input('h'); pause(); input('a'); pause()
  wait([[return require('cmp').visible()]], 'completion reopens')
  input('<CR>')
  wait('return vim.api.nvim_buf_line_count(0)==4', 'Enter does not confirm popup')
  check(call([[return vim.api.nvim_buf_get_lines(0,2,3,false)[1]=='sha']]), 'typed prefix preserved on Enter')
  input('jk')
  wait([[return vim.api.nvim_get_mode().mode=='n']], 'jk exits insertion')
end)
if not ok then
  print(err)
  local success, state=pcall(call, [[return {mode=vim.api.nvim_get_mode(),file=vim.api.nvim_buf_get_name(0),messages=vim.api.nvim_exec2('messages',{output=true}).output}]])
  if success then print(vim.inspect(state)) end
end
vim.fn.jobstop(child)
vim.cmd(ok and 'qa!' or 'cquit')
