local root = assert(vim.env.ZED_TEST_BUNDLE)
local project = vim.env.ZED_TEST_WORK .. '/project'
local special = project .. '/name with space | quote".txt'
vim.fn.writefile({ 'special filename' }, special)
local child = vim.fn.jobstart({ root .. '/run', project, '--embed', 'a.txt' }, { rpc = true })
local function call(code, ...) return vim.rpcrequest(child, 'nvim_exec_lua', code, { ... }) end
local function input(keys) vim.rpcrequest(child, 'nvim_input', keys) end
local function wait(code, label)
  assert(vim.wait(8000, function() return call(code) == true end, 25), label)
  print('PASS ' .. label)
end
local ok, err = pcall(function()
  vim.rpcrequest(child, 'nvim_ui_attach', 120, 40, { rgb = true })
  wait([[return #vim.api.nvim_list_wins()==1 and vim.bo.buftype=='']], 'single editor without sidebar')
  call([[vim.cmd('badd b.txt')]])
  input('<C-Tab>')
  wait([[return vim.api.nvim_buf_get_name(0):match('b.txt$')~=nil]], 'Ctrl-Tab switches forward')
  input('<C-S-Tab>')
  wait([[return vim.api.nvim_buf_get_name(0):match('a.txt$')~=nil]], 'Ctrl-Shift-Tab switches backward')
  input('i')
  wait([[return vim.api.nvim_get_mode().mode=='i']], 'insert mode')
  input('<C-Tab>')
  wait([[return vim.api.nvim_buf_get_name(0):match('b.txt$')~=nil and vim.api.nvim_get_mode().mode=='i']], 'switch preserves insert mode')
  input('<Tab>')
  wait([[return vim.api.nvim_get_current_line():match('^    ')~=nil]], 'ordinary Tab still indents')
  input('<C-S-Tab>')
  wait([[return vim.api.nvim_buf_get_name(0):match('a.txt$')~=nil and vim.api.nvim_get_mode().mode=='i']], 'unsaved file can be left in insert mode')
  input('<C-Tab>')
  wait([[return vim.api.nvim_buf_get_name(0):match('b.txt$')~=nil and vim.api.nvim_get_current_line():match('^    ')~=nil]], 'unsaved changes survive file cycling')
  input('jk')
  wait([[return vim.api.nvim_get_mode().mode=='n']], 'normal mode')
  call([[vim.bo.modified=false]])
  input('<C-\\>')
  wait([[return vim.bo.buftype=='terminal' and vim.api.nvim_get_mode().mode=='t']], 'independent shell opens')
  local shell = call('return vim.api.nvim_get_current_buf()')
  local job = call('return vim.b.terminal_job_id')
  input('<C-Tab>')
  wait([[return vim.bo.buftype=='' and vim.api.nvim_buf_get_name(0):match('a.txt$')~=nil]], 'terminal Ctrl-Tab switches editor file')
  assert(call('return vim.fn.bufwinid('..shell..')~=-1 and vim.b['..shell..'].terminal_job_id=='..job), 'shell process preserved')
  input(' e')
  wait([[return vim.bo.filetype=='zed_yazi' and vim.api.nvim_get_mode().mode=='t']], 'Yazi opens floating')
  wait([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),' '):find('a.txt',1,true)~=nil]], 'Yazi renders project files')
  input('q')
  wait([[return vim.bo.buftype=='' and #vim.api.nvim_list_wins()==2]], 'q closes Yazi and returns to editor')
  input(' e')
  wait([[return vim.bo.filetype=='zed_yazi']], 'Yazi reopens')
  wait([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),' '):find('a.txt',1,true)~=nil]], 'Yazi ready to select current file')
  input('<CR>')
  wait([[return vim.bo.buftype=='' and vim.api.nvim_buf_get_name(0):match('a.txt$')~=nil]], 'Yazi selection returns file to editor')
  input(' e')
  wait([[return vim.bo.filetype=='zed_yazi']], 'Yazi opens for switch cancellation')
  input('<C-Tab>')
  wait([[return vim.bo.buftype=='' and vim.api.nvim_buf_get_name(0):match('b.txt$')~=nil]], 'Ctrl-Tab closes Yazi and switches file')
  call([[local path=...; vim.api.nvim_win_set_buf(0,vim.fn.bufadd(path))]], special)
  input(' e')
  wait([[return vim.bo.filetype=='zed_yazi']], 'Yazi opens special filename')
  wait([[return table.concat(vim.api.nvim_buf_get_lines(0,0,-1,false),' '):find('name with space',1,true)~=nil]], 'special filename renders')
  input('<CR>')
  wait([[return vim.bo.buftype=='' and vim.api.nvim_buf_get_name(0):find('name with space | quote".txt',1,true)~=nil]], 'selected path preserves spaces and Ex metacharacters')
  assert(call('return vim.b['..shell..'].terminal_job_id=='..job), 'Yazi never replaces shell job')
end)
if not ok then
  print(err)
  print(vim.inspect(call([[return {mode=vim.api.nvim_get_mode(),file=vim.api.nvim_buf_get_name(0),messages=vim.api.nvim_exec2('messages',{output=true}).output,lines=vim.api.nvim_buf_get_lines(0,0,-1,false)}]])))
end
vim.fn.jobstop(child)
vim.cmd(ok and 'qa!' or 'cquit')
